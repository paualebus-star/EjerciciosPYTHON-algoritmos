x = float(input("Ingresar un número aleatorio: "))

import math
seno = math.sin(x)
coseno = math.cos(x)
tangente = math.tan(x)
raiz = math.sqrt(x)
logaritmo = math.log(x)

print (f"El seno del número ingresado es {seno}")
print (f"El coseno del número ingresado es {coseno}")
print (f"La tangente del número ingresado es {tangente}")
print (f"El raiz del número ingresado es {raiz}")
print (f"El logaritmo del número ingresado es {logaritmo}")